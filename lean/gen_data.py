#!/usr/bin/env python3
"""Transcribe analysis/sdpcspin-orders.json into the T3 Lean modules, AT CHECK TIME.

Writes lean/RouteOrders/Generated/{SdpcspinData,SdpcspinCounts}.lean, which lean/.gitignore ignores:
they are a re-derivable view of the committed artefact, never a committed second copy.

This script computes nothing about acceptance. It copies, per node, the groups, the edges and
full_ok (the left-hand side's inputs) and the artefact's counts and accepted bitsets (the right-hand
sides), and refuses an artefact that breaks a premise the Lean side relies on:
  * k == len(groups), every group index of an edge < k, every subset < 2^k;
  * piece letters unique per node among non-carried groups, at most one carried group;
  * both modes present (an artefact with a `carried:X` mode would need a third theorem family).
"""
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
SRC = os.path.join(REPO, 'analysis', 'sdpcspin-orders.json')
OUT = os.path.join(HERE, 'RouteOrders', 'Generated')


def die(msg):
    sys.exit(f'gen_data: {msg}')


def guard(short):
    # T3 TRUSTS THE COMPILER: each theorem carries its own native_decide axiom, and nothing else
    # beyond Lean's three standard axioms (no proof-hole axiom). The expected text is exact.
    return (f"/-- info: 'RouteOrders.Generated.{short}' depends on axioms: [propext,\n"
            f" Classical.choice,\n Quot.sound,\n {short}._native.native_decide.ax_1_1] -/\n"
            f"#guard_msgs in\n#print axioms RouteOrders.Generated.{short}\n")


def lean_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    raw = open(SRC, 'rb').read()
    md5 = hashlib.md5(raw).hexdigest()
    art = json.loads(raw)
    if art.get('schema') != 'route-orders/1':
        die(f'unexpected schema {art.get("schema")!r}')
    nodes = art['nodes']
    if not nodes:
        die('no nodes')
    data, counts = [], []
    for j, n in enumerate(nodes):
        gs = n['groups']
        k = len(gs)
        if n['k'] != k:
            die(f'{n["node"]}: k {n["k"]} != {k} groups')
        dealt = [g['piece'] for g in gs if not g['carried']]
        if len(set(dealt)) != len(dealt):
            die(f'{n["node"]}: duplicate dealt piece letters {dealt}')
        if sum(1 for g in gs if g['carried']) > 1:
            die(f'{n["node"]}: more than one carried group')
        for s, g in n['edges']:
            if not (0 <= g < k and 0 <= s < (1 << k)) or (s >> g) & 1:
                die(f'{n["node"]}: bad edge {[s, g]}')
        if set(n['counts']) != {'empty', 'next'} or set(n['accepted']) != {'empty', 'next'}:
            die(f'{n["node"]}: modes {sorted(n["counts"])} (only empty/next are supported)')
        name = f'n{j:02d}'
        pieces = ', '.join(f"'{g['piece']}'" for g in gs)
        carried = ', '.join('true' if g['carried'] else 'false' for g in gs)
        edges = ', '.join(f'({s}, {g})' for s, g in n['edges'])
        data.append(
            f'/-- {n["node"]} -/\n'
            f'def {name} : Node :=\n'
            f'  {{ name := {lean_str(n["node"])}, pieces := [{pieces}], carried := [{carried}],\n'
            f'    edges := [{edges}],\n'
            f'    fullOk := {"true" if n["full_ok"] else "false"},\n'
            f'    artEmpty := {n["counts"]["empty"]}, artNext := {n["counts"]["next"]},\n'
            f'    hexEmpty := {lean_str(n["accepted"]["empty"])},\n'
            f'    hexNext := {lean_str(n["accepted"]["next"])} }}\n')
        counts.append(
            f'/-- {n["node"]}: the artefact publishes {n["counts"]["empty"]} (empty) and '
            f'{n["counts"]["next"]} (next). -/\n'
            f'theorem {name}_empty : countEmpty {name} = {n["counts"]["empty"]} := by native_decide\n'
            f'theorem {name}_next : countNext {name} = {n["counts"]["next"]} := by native_decide\n'
            f'theorem {name}_bits_empty : bitsEmpty {name} = {name}.hexEmpty := by native_decide\n'
            f'theorem {name}_bits_next : bitsNext {name} = {name}.hexNext := by native_decide\n'
            + ''.join(guard(f'{name}_{m}') for m in ('empty', 'next', 'bits_empty', 'bits_next')))
    head = (f'-- GENERATED by lean/gen_data.py from analysis/sdpcspin-orders.json (md5 {md5}).\n'
            f'-- Do not edit and do not commit: lean/check.sh regenerates it.\n')
    os.makedirs(OUT, exist_ok=True)
    names = ', '.join(f'n{j:02d}' for j in range(len(nodes)))
    with open(os.path.join(OUT, 'SdpcspinData.lean'), 'w') as f:
        f.write(head + 'import RouteOrders.NodeData\n\nnamespace RouteOrders.Generated\n'
                'open RouteOrders.NodeData\n\n' + '\n'.join(data) +
                f'\ndef nodes : List Node := [{names}]\n\n'
                f'def artefactMd5 : String := {lean_str(md5)}\n\nend RouteOrders.Generated\n')
    with open(os.path.join(OUT, 'SdpcspinCounts.lean'), 'w') as f:
        f.write(head + 'import RouteOrders.Generated.SdpcspinData\n\nnamespace RouteOrders.Generated\n'
                'open RouteOrders.NodeData\n\n' + '\n'.join(counts) + '\nend RouteOrders.Generated\n')
    print(f'gen_data: {len(nodes)} nodes from {os.path.relpath(SRC, REPO)} (md5 {md5})')


if __name__ == '__main__':
    main()
