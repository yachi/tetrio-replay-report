def slug(g): return re.sub(r"[^a-zA-Z0-9]+", "_", g).strip("_").lower()[:60]


def emit_claims(path, builders, comment):
    claims = json.load(open(path))
    lines = [f"// {comment} — GENERATED by codegen_dafny.py. DO NOT EDIT.", 'include "Facts.dfy"', ""]
    mapping = []
    for c in claims:
        cid = c["id"]
        ens = builders[cid]()
        name = f"{cid}_{slug(c['english_gloss'])}"
        lines += [f"// {cid}: {c['english_gloss']}", f"// python_check: {c['python_check']}",
                  f"lemma {name}()", f"  ensures {ens}", "{", "}", ""]
        mapping.append({"id": cid, "lemma": name})
    return "\n".join(lines), mapping


