#!/usr/bin/env python3
"""codegen_dafny.py — trust chain for the full 2026-07-24 report (52 claims).

Reads facts.json + claims-narrative.json (C001-C028) + claims-coaching.json
(R001-R024) and GENERATES all Dafny under ./dafny (Facts.dfy, Claims_narrative.dfy,
Claims_coaching.dfy). Proven design carried over from the 07-22 report:

  * FLAT named scalar consts (no seq/datatype indexing) → literal-arithmetic proofs.
  * BALANCED (log-depth) expression trees for every sum/count/conjunction so deep
    ground folds don't overflow Boogie's recursive AST visitor.
  * ONE empty-body lemma per claim; ensures = faithful translation of python_check.
  * Winner/loser-relative reads select via if/else on the winner-string const.

Data emitted = only fields the 52 claims reference: per-round apm/pps/vs/lifetime/
maxspike/topcombo/tspins/topbtb/pieces/garbageAttack/finesseFaults/kills/holds/
garbagereceived/quads/tspinDoubles/tspinTriples/allclear (+ garbage_events amt for
BOTH players), per-match leaderboard apm/pps/kills, and match winner/score/index/
round-count + per-round winner. Everything else in facts.json is omitted.

Usage: python3 codegen_dafny.py
"""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "dafny")
facts = json.load(open(os.path.join(HERE, "facts.json")))
MS = facts["matches"]

RF = {
    "apm": lambda p: p["apm_x1000"], "pps": lambda p: p["pps_x1000"], "vs": lambda p: p["vs_x1000"],
    "lifetime": lambda p: p["lifetime"], "maxspike": lambda p: p["maxspike"],
    "topcombo": lambda p: p["topcombo"], "tspins": lambda p: p["tspins"], "topbtb": lambda p: p["topbtb"],
    "pieces": lambda p: p["pieces"], "garbageAttack": lambda p: p["garbage_attack"],
    "finesseFaults": lambda p: p["finesse_faults"], "kills": lambda p: p["kills"],
    "holds": lambda p: p["holds"], "garbagereceived": lambda p: p["garbagereceived"],
    "quads": lambda p: p["clears"]["quads"], "tspinDoubles": lambda p: p["clears"]["tspin_doubles"],
    "tspinTriples": lambda p: p["clears"]["tspin_triples"], "allclear": lambda p: p["clears"]["allclear"],
}
LBF = {"apm": lambda e: e["apm_x1000"], "pps": lambda e: e["pps_x1000"], "kills": lambda e: e["kills"]}
RFIELDS = list(RF.keys())
LBFIELDS = list(LBF.keys())
ROUNDS = [(mi, ri) for mi, m in enumerate(MS) for ri in range(len(m["rounds"]))]
ALLPP = [(mi, ri, pl) for (mi, ri) in ROUNDS for pl in ("yachi", "pinglamb")]


def pobj(mi, ri, pl):
    return MS[mi]["rounds"][ri]["players"][pl]


def lbobj(mi, pl):
    return MS[mi]["leaderboard"][pl]


# ---------------- Facts.dfy ----------------

def emit_facts():
    L = ["// Facts.dfy — GENERATED by codegen_dafny.py from facts.json. DO NOT EDIT.",
         "// Flat named scalar consts, one per datum referenced by the 52 claims.",
         "// Every literal is emitted from facts.json (no hand-typed data).",
         "// Per-round fields: " + ", ".join(RFIELDS) + " (+ garbage_events amt for both",
         "// players). Per-match leaderboard: apm/pps/kills. Match winner/score/index/",
         "// nrounds + per-round winner. All other facts.json fields are omitted.", ""]
    L.append(f"const nmatches: int := {len(MS)}")
    for mi, m in enumerate(MS):
        L.append(f"const m{mi}_index: int := {m['index']}")
        L.append(f'const m{mi}_winner: string := "{m["winner"]}"')
        L.append(f"const m{mi}_scoreYachi: int := {m['score']['yachi']}")
        L.append(f"const m{mi}_scorePinglamb: int := {m['score']['pinglamb']}")
        L.append(f"const m{mi}_nrounds: int := {len(m['rounds'])}")
        for pl in ("yachi", "pinglamb"):
            for f in LBFIELDS:
                L.append(f"const m{mi}_lb_{pl}_{f}: int := {LBF[f](lbobj(mi, pl))}")
        for ri, r in enumerate(m["rounds"]):
            L.append(f'const m{mi}_r{ri}_winner: string := "{r["winner"]}"')
            for pl in ("yachi", "pinglamb"):
                p = r["players"][pl]
                for f in RFIELDS:
                    L.append(f"const m{mi}_r{ri}_{pl}_{f}: int := {RF[f](p)}")
                for k, e in enumerate(p["garbage_events"]):
                    L.append(f"const m{mi}_r{ri}_{pl}_ge{k}: int := {e['amt']}")
    L.append("")
    return "\n".join(L)


# ---------------- expression primitives ----------------

def bal(op, terms):
    terms = list(terms)
    if not terms:
        return "0"
    if len(terms) == 1:
        return terms[0]
    mid = len(terms) // 2
    return f"({bal(op, terms[:mid])} {op} {bal(op, terms[mid:])})"


def S(mi, ri, pl, f): return f"m{mi}_r{ri}_{pl}_{f}"
def WR(mi, ri): return f"m{mi}_r{ri}_winner"
def WM(mi): return f"m{mi}_winner"
def SC(mi, w): return f"m{mi}_score{w}"
def NR(mi): return f"m{mi}_nrounds"
def MI(mi): return f"m{mi}_index"
def LB(mi, pl, f): return f"m{mi}_lb_{pl}_{f}"


def wval(mi, ri, f):
    return f'(if {WR(mi,ri)} == "yachi" then {S(mi,ri,"yachi",f)} else {S(mi,ri,"pinglamb",f)})'


def lval(mi, ri, f):
    return f'(if {WR(mi,ri)} == "yachi" then {S(mi,ri,"pinglamb",f)} else {S(mi,ri,"yachi",f)})'


def roundmax_lt(mi, ri):
    y, p = S(mi, ri, "yachi", "lifetime"), S(mi, ri, "pinglamb", "lifetime")
    return f"(if {y} >= {p} then {y} else {p})"


def geSum(mi, ri, pl):
    return bal("+", [f"m{mi}_r{ri}_{pl}_ge{k}" for k in range(len(pobj(mi, ri, pl)["garbage_events"]))])


def sum_rf(pl, f, scope=None):
    scope = scope or ROUNDS
    return bal("+", [S(mi, ri, pl, f) for (mi, ri) in scope]), sum(RF[f](pobj(mi, ri, pl)) for (mi, ri) in scope)


def sumsq_rf(pl, f):
    return (bal("+", [f"({S(mi,ri,pl,f)} * {S(mi,ri,pl,f)})" for (mi, ri) in ROUNDS]),
            sum(RF[f](pobj(mi, ri, pl)) ** 2 for (mi, ri) in ROUNDS))


def count_expr(conds):
    return bal("+", [f"(if {c} then 1 else 0)" for c, _ in conds]), sum(1 for _, b in conds if b)


def eq(a, b): return f"({a} == {b})"
def andjoin(parts): return bal("&&", [f"({p})" for p in parts])


def max_pp_is(field, V, achieve):
    ai, ari, apl = achieve
    return f"({S(ai,ari,apl,field)} == {V}) && ({bal('&&', [f'{S(mi,ri,pl,field)} <= {V}' for (mi,ri,pl) in ALLPP])})"


def max_player_is(pl, field, V, achieve):
    scope = [(mi, ri) for (mi, ri) in ROUNDS]
    ai, ari = achieve
    return f"({S(ai,ari,pl,field)} == {V}) && ({bal('&&', [f'{S(mi,ri,pl,field)} <= {V}' for (mi,ri) in scope])})"


def rmax_is(V, achieve):
    return f"({roundmax_lt(*achieve)} == {V}) && ({bal('&&', [f'{roundmax_lt(mi,ri)} <= {V}' for (mi,ri) in ROUNDS])})"


def rmin_is(V, achieve):
    return f"({roundmax_lt(*achieve)} == {V}) && ({bal('&&', [f'{roundmax_lt(mi,ri)} >= {V}' for (mi,ri) in ROUNDS])})"


def lb_max_is(field, V, achieve):
    ai, apl = achieve
    scope = [(mi, pl) for mi in range(len(MS)) for pl in ("yachi", "pinglamb")]
    return f"({LB(ai,apl,field)} == {V}) && ({bal('&&', [f'{LB(mi,pl,field)} <= {V}' for (mi,pl) in scope])})"


def variance(pl, field):
    sq, _ = sumsq_rf(pl, field)
    s, _ = sum_rf(pl, field)
    return f"(50 * {sq} - {s} * {s})"


