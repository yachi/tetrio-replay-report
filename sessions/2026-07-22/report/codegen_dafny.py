ALLPP = [(mi, ri, pl) for (mi, ri) in ROUNDS for pl in ("yachi", "pinglamb")]


def pobj(mi, ri, pl):
    return MS[mi]["rounds"][ri]["players"][pl]


# =====================================================================
# Facts.dfy — flat scalar consts
# =====================================================================

def emit_facts():
    L = []
    L.append("// Facts.dfy — GENERATED by codegen_dafny.py from facts.json. DO NOT EDIT.")
    L.append("// Flat named scalar consts, one per datum referenced by the 54 claims.")
    L.append("// Every literal is emitted from facts.json (no hand-typed data).")
    L.append("// Naming: m{match_idx0}_r{round_idx0}_{player}_{field}. Winner/score/")
    L.append("// round-count as m{mi}_winner / m{mi}_scoreYachi / m{mi}_scorePinglamb /")
    L.append("// m{mi}_nrounds / m{mi}_r{ri}_winner. yachi garbage_events amt as")
    L.append("// m{mi}_r{ri}_yachi_ge{k} (only R019 reads them; pinglamb ge omitted).")
    L.append("// Omitted from facts.json (no claim references): garbagesent, kills,")
    L.append("// inputs, leaderboard block, per-match ts, garbage_events.frame,")
    L.append("// clears singles/doubles/triples/tspin_singles/mini_*.")
    L.append("")
    L.append(f"const nmatches: int := {len(MS)}")
    for mi, m in enumerate(MS):
        L.append(f'const m{mi}_winner: string := "{m["winner"]}"')
        L.append(f"const m{mi}_scoreYachi: int := {m['score']['yachi']}")
        L.append(f"const m{mi}_scorePinglamb: int := {m['score']['pinglamb']}")
        L.append(f"const m{mi}_nrounds: int := {len(m['rounds'])}")
        for ri, r in enumerate(m["rounds"]):
            L.append(f'const m{mi}_r{ri}_winner: string := "{r["winner"]}"')
            for pl in ("yachi", "pinglamb"):
                p = r["players"][pl]
                for f in INT_FIELDS:
                    L.append(f"const m{mi}_r{ri}_{pl}_{f}: int := {PY[f](p)}")
                L.append(f"const m{mi}_r{ri}_{pl}_alive: bool := {'true' if p['alive'] else 'false'}")
            for k, e in enumerate(r["players"]["yachi"]["garbage_events"]):
                L.append(f"const m{mi}_r{ri}_yachi_ge{k}: int := {e['amt']}")
    L.append("")
    return "\n".join(L)


# =====================================================================
# Dafny expression primitives over the flat consts
# =====================================================================

def S(mi, ri, pl, field):
    return f"m{mi}_r{ri}_{pl}_{field}"


def WR(mi, ri):
    return f"m{mi}_r{ri}_winner"


def WM(mi):
    return f"m{mi}_winner"


def SC(mi, which):
    return f"m{mi}_score{which}"


def NR(mi):
    return f"m{mi}_nrounds"


def wval(mi, ri, field):
    """r['players'][r['winner']][field] — selected by the winner-string const."""
    return (f"(if {WR(mi,ri)} == \"yachi\" then {S(mi,ri,'yachi',field)} "
            f"else {S(mi,ri,'pinglamb',field)})")


def lval(mi, ri, field):
    """the non-winner player's field."""
    return (f"(if {WR(mi,ri)} == \"yachi\" then {S(mi,ri,'pinglamb',field)} "
            f"else {S(mi,ri,'yachi',field)})")


def roundmax_lt(mi, ri):
    """round duration = max of the two players' lifetime."""
    y, p = S(mi, ri, "yachi", "lifetime"), S(mi, ri, "pinglamb", "lifetime")
    return f"(if {y} >= {p} then {y} else {p})"


def bal(op, terms):
    """Balanced (log-depth) associative fold. Deep LEFT-nested chains overflow
    Boogie's recursive AST visitor (stack overflow); a balanced tree keeps depth
    at O(log n) so 1000+-term ground sums/conjunctions verify safely."""
    terms = list(terms)
    if len(terms) == 1:
        return terms[0]
    mid = len(terms) // 2
    return f"({bal(op, terms[:mid])} {op} {bal(op, terms[mid:])})"


def sum_field(pl, field, scope=None):
    scope = scope or ROUNDS
    terms = [S(mi, ri, pl, field) for (mi, ri) in scope]
    val = sum(PY[field](pobj(mi, ri, pl)) for (mi, ri) in scope)
    return bal("+", terms), val


def sum_sq_field(pl, field):
    terms = [f"({S(mi,ri,pl,field)} * {S(mi,ri,pl,field)})" for (mi, ri) in ROUNDS]
    val = sum(PY[field](pobj(mi, ri, pl)) ** 2 for (mi, ri) in ROUNDS)
    return bal("+", terms), val


def sum_field_pp(field):
    terms = [S(mi, ri, pl, field) for (mi, ri, pl) in ALLPP]
    val = sum(PY[field](pobj(mi, ri, pl)) for (mi, ri, pl) in ALLPP)
    return bal("+", terms), val


def count_expr(conds):
    terms = [f"(if {c} then 1 else 0)" for c, _ in conds]
    val = sum(1 for _, b in conds if b)
    return bal("+", terms), val


def all_le(field, scope_pp, V):
    return bal("&&", [f"{S(mi,ri,pl,field)} <= {V}" for (mi, ri, pl) in scope_pp])


def all_ge(field, scope_pp, V):
    return bal("&&", [f"{S(mi,ri,pl,field)} >= {V}" for (mi, ri, pl) in scope_pp])


def max_is(field, V, scope_pp, achieve):
    ai, ari, apl = achieve
    return f"({S(ai,ari,apl,field)} == {V}) && ({all_le(field, scope_pp, V)})"


def eq(a, b):
    return f"({a} == {b})"


def andjoin(parts):
    return bal("&&", [f"({p})" for p in parts])


