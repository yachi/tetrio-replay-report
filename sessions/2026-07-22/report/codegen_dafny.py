def slug(gloss):
    return re.sub(r"[^a-zA-Z0-9]+", "_", gloss).strip("_").lower()[:60]


def emit_claims(claims_path, builders, module_comment):
    claims = json.load(open(claims_path))
    lines = [f"// {module_comment} — GENERATED by codegen_dafny.py. DO NOT EDIT.",
             'include "Facts.dfy"', ""]
    mapping = []
    for c in claims:
        cid = c["id"]
        ens = builders[cid]()
        name = f"{cid}_{slug(c['english_gloss'])}"
        lines.append(f"// {cid}: {c['english_gloss']}")
        lines.append(f"// python_check: {c['python_check']}")
        lines.append(f"lemma {name}()")
        lines.append(f"  ensures {ens}")
        lines.append("{")
        lines.append("}")
        lines.append("")
        mapping.append({"id": cid, "lemma": name})
    return "\n".join(lines), mapping


