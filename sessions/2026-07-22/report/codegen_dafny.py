#!/usr/bin/env python3
"""codegen_dafny.py — the trust chain.

Reads facts.json + claims-narrative.json + claims-coaching.json and GENERATES all
Dafny source under ./dafny. NO per-round statistic is ever hand-typed in a .dfy
file: every data literal is emitted here from facts.json.

Design
------
* Facts.dfy — FLAT named scalar consts, one per datum the 54 claims reference:
      const m{mi}_r{ri}_{player}_{field}: int := <value>;   // from facts.json
      const m{mi}_r{ri}_winner: string := "..."; etc.
  A flat const is a transparent literal to Z3, so every proof below reduces to
  literal arithmetic — no seq indexing, no datatype destructors, no recursion,
  no proof hints. (An earlier nested `seq<Match>` design made Z3 deep-index one
  giant literal and timed out; flat consts fix that at the root.)
  Fields carried = only those referenced by the claims (omissions documented in
  the Facts.dfy header). ge (garbage_events amt) consts are emitted for yachi
  only, since R019 is the sole claim reading them.
* Claims_narrative.dfy / Claims_coaching.dfy — ONE lemma per claim, id-named,
  whose ensures-clause is a faithful translation of that claim's python_check
  over the flat consts. Bodies are empty; the consts evaluate directly.
* Winner/loser-relative reads (`r['players'][r['winner']]`) are translated with
  an if-then-else on the winner-string const, so a mutated winner still changes
  which datum is selected (mutation-faithful).

Usage: python3 codegen_dafny.py            # writes dafny/*.dfy + claims-proof-map.json
"""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
