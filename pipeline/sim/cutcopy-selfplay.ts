/**
 * 千鳥格子 (Cut Copy) in COLD-CLEAR SELF-PLAY: the games in which the bot, playing alone, built one, as playable
 * replays (`analysis/cutcopy-selfplay.json`).
 *
 *   bun pipeline/sim/emit-cutcopy-selfplay.ts --games games.jsonl --coach-seed 0 --out analysis/cutcopy-selfplay.json
 *   bun pipeline/sim/emit-cutcopy-selfplay.ts --rebuild --out analysis/cutcopy-selfplay.json
 *
 * NOT CORPUS DATA, NOT A SOURCE'S DRAWING AND NOT OURS. A bot (cold-clear, pinned rev, the cc-coach patch and
 * harness in tools/cc-coach) played these games alone from an empty board, with no garbage and no opponent. The
 * artefact says `report_eligible: false`, `constructed: true` and `selfplay: true`.
 *
 * Two steps, and only the second is re-run by the test:
 *
 * 1. SCAN (`scan`, the emitter's `--games`): every game of a cc-coach COACH_MODE=selfplay JSONL replayed through
 *    the engine (`cc-selfplay.replayGame`) and the corpus classifier `technique-facts.classify(CUTCOPY, …)` run over
 *    them unchanged. Its summary and its hit list go into the artefact as `scan`. The JSONL is not committed (it
 *    is the bot's whole output, regenerated by the commands in tools/cc-coach/FINDINGS-cutcopy-selfplay.md); its
 *    md5 is recorded, and the scan's figures are re-derived only by re-running the emitter on it.
 * 2. BUILD (`build`): for every game holding a hit, cold-clear's own placements up to the last lock that decides a
 *    hit's follow-up, plus `TAIL` more, are committed INSIDE the artefact, replayed through the engine again, and
 *    classified again; the hits must be exactly the scan's for that game, or the build throws. Every timeline is
 *    the engine's own (`instrumentEngine`) and must round-trip (`assertRoundTrip`). `--rebuild` and the test run
 *    this from the committed placements alone and must reproduce the artefact byte for byte.
 */
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { replayGame, digestOf, SELFPLAY_ENGINE_ROUTES, type CcGame, type CcStep } from './cc-selfplay.ts';
import { classify, loadTranscription, type Hit } from './technique-facts.ts';
import { CUTCOPY } from './technique-profile-cutcopy.ts';
import { md5Files } from './route-facts.ts';
import { assertRoundTrip, LOCK_FIELDS, SHAPES, WIDTH, ROWS, VISIBLE_ROWS } from './emit-replay.ts';
import { DEMO_OPTIONS, FRAMES_PER_INPUT, demoDate } from './route-demos.ts';
import { TL_DEFAULTS } from './oracle-source.ts';

const SIM = import.meta.dir;
const REPO = `${SIM}/../..`;
const md5 = (b: string | Buffer) => createHash('md5').update(b).digest('hex');

export const SELFPLAY_PATH = `${REPO}/analysis/cutcopy-selfplay.json`;
/** placements committed after the last lock that decides a hit's follow-up */
export const TAIL = 2;
export const HASH_FILES = {
  replay: [`${SIM}/cc-selfplay.ts`, `${SIM}/route-demos.ts`, `${SIM}/emit-replay.ts`],
  build: [`${SIM}/cutcopy-selfplay.ts`, `${SIM}/emit-cutcopy-selfplay.ts`],
  harness: [`${REPO}/tools/cc-coach/cc-coach.rs`, `${REPO}/tools/cc-coach/cold-clear-coach.patch`,
            `${REPO}/tools/cc-coach/Cargo.lock`],
};
/** what the pilot ran; the emitter's flags may override the COACH_SEED, the rest is read off the games */
export const BOT = {
  name: 'cold-clear',
  repo: 'https://github.com/MinusKelvin/cold-clear',
  rev: '279edd7c3177ff8077f6a930193397814b281f27',
  patch: 'tools/cc-coach/cold-clear-coach.patch',
  harness: 'tools/cc-coach/cc-coach.rs',
  mode: 'COACH_MODE=selfplay',
};

export function inputMd5s() {
  return {
    transcription_md5: md5(readFileSync(CUTCOPY.transcriptionPath)),
    replay_md5: md5Files(HASH_FILES.replay),
    build_md5: md5Files(HASH_FILES.build),
    harness_md5: md5Files(HASH_FILES.harness),
    classifier_md5: md5Files(CUTCOPY.hashFiles.classifier),
  };
}

const hitOf = (h: Hit) => ({ variant: h.variant, lock: h.lock, hand: h.mirrored ? 'mirrored' : 'as_drawn',
                             in_opener: h.in_opener, window: h.window_letters, followup: h.followup });
const seedOf = (h: Hit) => Number(h.file.slice('seed-'.length));
/** the last lock a hit's outcome reads: its follow-up's deciding lock, else the hit itself */
const decides = (h: { lock: number; followup: { lock: number | null } }) => Math.max(h.lock, h.followup.lock ?? h.lock);

/** Step 1: every game, replayed and classified. */
export function scan(games: CcGame[]) {
  const tr = loadTranscription(CUTCOPY.transcriptionPath);
  const rs = games.map(g => replayGame(g));
  const cls = classify(CUTCOPY, tr, games.map((g, i) => digestOf(g, rs[i]!, i)));
  const cuts: Record<string, number> = {};
  for (const r of rs) if (r.cut) cuts[r.cut.why] = (cuts[r.cut.why] ?? 0) + 1;
  const nodes = [...new Set(games.map(g => g.nodes))];
  if (nodes.length !== 1) throw new Error(`selfplay: games ran at different node counts ${nodes}`);
  const per = [...new Set(games.map(g => g.steps.length))];
  const seeds = games.map(g => g.seed);
  if (seeds.some((x, i) => x !== seeds[0]! + i)) throw new Error('selfplay: the games are not consecutive seeds');
  return {
    summary: {
      games: games.length,
      seeds: [seeds[0], seeds[seeds.length - 1]],
      cc_nodes: nodes[0],
      pieces_per_game: per.length === 1 ? per[0] : per,
      games_complete: rs.filter(r => r.ok).length,
      pieces_cc: rs.reduce((a, r) => a + r.steps.length, 0),
      pieces_replayed: rs.reduce((a, r) => a + r.locks.length, 0),
      cuts,
      scored_tsds: rs.reduce((a, r) => a + r.locks.filter(l => l.piece === 'T' && l.spin === 'full' && l.cleared === 2).length, 0),
      hits: cls.hits.map(h => ({ seed: seedOf(h), ...hitOf(h) })),
    },
    replayed: rs,
  };
}

/** Which games to commit, and how many of their placements. */
export function select(games: CcGame[], summary: ReturnType<typeof scan>['summary'], replayed: ReturnType<typeof replayGame>[]) {
  const seeds = [...new Set(summary.hits.map(h => h.seed))].sort((a, b) => a - b);
  return seeds.map(seed => {
    const k = games.findIndex(g => g.seed === seed);
    const g = games[k]!, r = replayed[k]!;
    const end = Math.min(Math.max(...summary.hits.filter(h => h.seed === seed).map(decides)) + TAIL, r.locks.length - 1);
    const steps: CcStep[] = r.steps.slice(0, end + 1).map(s => ({ piece: s.piece, hold: s.hold, cells: s.cells,
                                                                  lines: s.lines, tspin: s.tspin, kind: s.kind }));
    return { seed, id: g.id ?? `sp-${seed}`, queue: g.queue, steps };
  });
}

/** Step 2: the artefact, from committed placements. `provenance` and `summary` are carried as given. */
export function build(provenance: any, summary: any, games: { seed: number; id: string; queue: string; steps: CcStep[] }[]) {
  const tr = loadTranscription(CUTCOPY.transcriptionPath);
  const cc: CcGame[] = games.map(g => ({ seed: g.seed, id: g.id, queue: g.queue, steps: g.steps }));
  const rs = cc.map(g => replayGame(g));
  rs.forEach((r, i) => {
    if (!r.ok) throw new Error(`selfplay: seed ${cc[i]!.seed} committed placements do not replay: ${r.cut!.why} ${r.cut!.where}`);
    if (r.locks.length !== cc[i]!.steps.length) throw new Error(`selfplay: seed ${cc[i]!.seed} lock count drift`);
    assertRoundTrip(`selfplay seed ${cc[i]!.seed}`, r.timeline.seq, r.timeline as any);
  });
  const cls = classify(CUTCOPY, tr, cc.map((g, i) => digestOf(g, rs[i]!, i)));
  const out = games.map((g, i) => {
    const hits = cls.hits.filter(h => seedOf(h) === g.seed).map(hitOf);
    const want = summary.hits.filter((h: any) => h.seed === g.seed).map(({ seed, ...h }: any) => h);
    if (JSON.stringify(hits) !== JSON.stringify(want))
      throw new Error(`selfplay: seed ${g.seed}: committed placements give hits ${JSON.stringify(hits)}, the scan ${JSON.stringify(want)}`);
    const t = rs[i]!.timeline;
    const events = t.locks.flatMap((lk, j) => lk[3] > 0 && lk[2] > 0
      ? [{ lock: j, kind: (lk[3] === 1 ? 'mini ' : '') + (['', 'TSS', 'TSD', 'TST'][lk[2]] ?? `T${lk[2]}`), spin: lk[3], lines: lk[2] }]
      : []);
    return { node: `selfplay.${g.seed}`, seed: g.seed, id: g.id, hits, placements: g.steps,
             seq: t.seq, frames: t.frames, locks: t.locks, events };
  });
  const seen = new Set(out.map(g => g.seed));
  for (const h of summary.hits) if (!seen.has(h.seed)) throw new Error(`selfplay: the scan's hit at seed ${h.seed} has no committed game`);
  return {
    schema: 'technique-selfplay/1',
    report_eligible: false,
    constructed: true,
    selfplay: true,
    technique: 'cutcopy',
    means: 'Games cold-clear played ALONE (self-play, no garbage, no opponent) in which the corpus classifier '
      + '(technique-facts.ts classify, the profile analysis/cutcopy-facts.json is built with) finds a 千鳥格子 '
      + 'window: the bot\'s own placements up to the last lock deciding a hit\'s follow-up and a few more, replayed '
      + 'through the vendored Triangle engine, which is the arbiter, and recorded as a timeline a page can play.',
    not_eligible_because: 'played by a bot, not by either player, and not any source\'s drawing: no claim id, no '
      + 'badge, no figure in any count of the corpus.',
    caveat: 'one search sample per game (cold-clear\'s search is seeded by COACH_SEED), an unconverged node budget, '
      + 'no garbage: these games say nothing about how often a person, or the bot under pressure, builds one.',
    rules: [
      'every placement is cold-clear\'s; the path to it is the engine\'s (reach + inputsOf, SRS+, 180 allowed), and '
        + 'for a T the first path whose engine spin equals cold-clear\'s',
      'the engine is the arbiter: each lock must land on cold-clear\'s cells with cold-clear\'s line count, or the game is cut',
      'the hits are the corpus classifier\'s, run unchanged on the replayed games, and must equal the scan\'s',
      `the committed placements stop ${TAIL} locks after the last lock that decides a hit's follow-up`,
    ],
    provenance,
    scan: summary,
    tail: TAIL,
    engine: { options: DEMO_OPTIONS, kickset: TL_DEFAULTS.kickset, allow180: TL_DEFAULTS.allow180,
              date: demoDate(SELFPLAY_ENGINE_ROUTES).toISOString(), frames_per_input: FRAMES_PER_INPUT },
    inputs: inputMd5s(),
    board: { width: WIDTH, rows: ROWS, visible_rows: VISIBLE_ROWS,
             coords: 'y-UP: row 0 is the bottom row', cell: 'yUp * width + x' },
    lock_fields: LOCK_FIELDS,
    shapes: SHAPES,
    games: out,
  };
}

/** Rebuild from a committed artefact's own placements. */
export function rebuild(committed: any) {
  return build(committed.provenance, committed.scan,
               committed.games.map((g: any) => ({ seed: g.seed, id: g.id, queue: g.seq, steps: g.placements })));
}

/** One game per line, metadata pretty-printed. */
export function serialise(out: any): string {
  const { games, ...rest } = out;
  const head = JSON.stringify({ ...rest, games: '\u0000' }, null, 1);
  return head.replace('"\\u0000"', '[\n' + games.map((d: any) => '  ' + JSON.stringify(d)).join(',\n') + '\n ]') + '\n';
}
