/**
 * Generates `oracle-rs/src/data.rs` — the piece shapes, the SRS+ kick tables and the T corner table the
 * Rust oracle reads — from the vendored Triangle engine's own data modules, so the Rust port never
 * carries a hand copy of them. `oracle-native.test.ts` holds the committed file equal to a fresh render.
 *
 *   bun pipeline/sim/gen-oracle-rs-data.ts --write   # rewrite src/data.rs
 *   bun pipeline/sim/gen-oracle-rs-data.ts --check   # exit 1 when it is stale
 *
 * Only the rule set the oracle accepts is rendered (`SRS+` kicks, `T-spins` spin bonuses, the seven
 * standard pieces); every assumption the Rust side relies on is asserted here, so a re-vendored engine
 * that breaks one fails generation rather than producing a different table.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { tetrominoes } from './vendor/teto/engine/utils/tetromino/data.mjs';
import { cornerTable, kicks, spinbonusRules } from './vendor/teto/engine/utils/kicks/data.mjs';

export const DATA_RS = join(import.meta.dir, 'oracle-rs/src/data.rs');
/** Piece index order used by the Rust side and the FFI encoding (cell codes are index + 1). */
export const PIECES = ['i', 'j', 'l', 'o', 's', 't', 'z'] as const;

const fail = (m: string): never => { throw new Error(`gen-oracle-rs-data: ${m}`); };
const int = (v: unknown, what: string): number => (Number.isInteger(v) ? (v as number) : fail(`${what} is not an integer: ${v}`));

export function render(): string {
  const out: string[] = [
    '// @generated by pipeline/sim/gen-oracle-rs-data.ts from the vendored Triangle engine',
    '// (pipeline/sim/vendor/teto/engine/utils/{tetromino,kicks}/data.mjs). Do not edit by hand.',
    '',
    '/// Piece order: I J L O S T Z (cell code = index + 1).',
    `pub const PIECES: [u8; 7] = [${PIECES.map((p) => `b'${p}'`).join(', ')}];`,
    '',
  ];

  // shapes: width and the four rotation states' block offsets (x, y-down within the matrix)
  const widths: number[] = [];
  const states: string[] = [];
  for (const p of PIECES) {
    const m = (tetrominoes as any)[p]?.matrix ?? fail(`no tetromino ${p}`);
    widths.push(int(m.w, `${p}.w`));
    if (m.data.length !== 4) fail(`${p} has ${m.data.length} states`);
    const st = m.data.map((s: any[], r: number) => {
      if (s.length !== 4) fail(`${p} state ${r} has ${s.length} blocks`);
      return `[${s.map((b: any[], i: number) => `(${int(b[0], `${p}[${r}][${i}].x`)}, ${int(b[1], `${p}[${r}][${i}].y`)})`).join(', ')}]`;
    });
    states.push(`    [${st.join(', ')}],`);
    if ((tetrominoes as any)[p].spinbonus_override) fail(`${p} has a spinbonus_override`);
  }
  out.push(`pub const WIDTH: [i32; 7] = [${widths.join(', ')}];`);
  out.push('pub const STATES: [[[(i32, i32); 4]; 4]; 7] = [', ...states, '];', '');

  // kicks: SRS+, per piece the table the engine picks (`${p}_kicks` when present, else `kicks`), by id
  // from*4+to; None is an id the chosen table lacks, which makes the engine's lookup throw (→ no kick)
  const table = (kicks as any)['SRS+'] ?? fail('no SRS+ kick table');
  const sp = table.spawn_rotation ?? {};
  for (const p of PIECES) if (sp[p] !== undefined && sp[p] !== 0) fail(`spawn_rotation[${p}] = ${sp[p]}`);
  const ids: string[] = [];
  for (let f = 0; f < 4; f++) for (let t = 0; t < 4; t++) ids.push(`${f}${t}`);
  const kickRows: string[] = [];
  for (const p of PIECES) {
    const set = `${p}_kicks` in table ? table[`${p}_kicks`] : table.kicks;
    const row = ids.map((id) => {
      const k = set[id];
      if (k === undefined) return 'None';
      if (!Array.isArray(k)) fail(`${p} kick ${id} is not a list`);
      return `Some(&[${k.map((d: any[], i: number) => `(${int(d[0], `${p} ${id}[${i}].dx`)}, ${int(d[1], `${p} ${id}[${i}].dy`)})`).join(', ')}])`;
    });
    kickRows.push(`    [${row.join(', ')}],`);
  }
  out.push('/// Kick tests (dx, dy) by piece and rotation id from*4+to.');
  out.push('pub const KICKS: [[Option<&[(i32, i32)]>; 16]; 7] = [', ...kickRows, '];', '');

  // T corner table: per rotation four (dx, dy, front_a, front_b)
  const ct = cornerTable.t ?? fail('no cornerTable.t');
  if (ct.length !== 4) fail('cornerTable.t does not have four rotations');
  out.push('pub const T_CORNERS: [[(i32, i32, i32, i32); 4]; 4] = [');
  for (const rot of ct) {
    if (rot.length !== 4) fail('a cornerTable.t rotation does not have four corners');
    out.push(`    [${rot.map((c: any[]) => `(${c.map((v, i) => int(v, `corner ${i}`)).join(', ')})`).join(', ')}],`);
  }
  out.push('];', '');

  const rules = (spinbonusRules as any)['T-spins'] ?? fail('no T-spins spin bonus rules');
  if (!rules.types_mini?.includes('t')) fail('T-spins types_mini does not include t');
  return out.join('\n');
}

if (import.meta.main) {
  const want = render();
  if (process.argv.includes('--write')) { writeFileSync(DATA_RS, want); console.log(`wrote ${DATA_RS}`); }
  else if (process.argv.includes('--check')) {
    const have = readFileSync(DATA_RS, 'utf8');
    if (have !== want) { console.error(`${DATA_RS} is stale; run with --write`); process.exit(1); }
    console.log('data.rs is current');
  } else { process.stdout.write(want); }
}
